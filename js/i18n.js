  // "21 год, 3 года, 19 лет": Slavic plurals depend on the number, so a
  // count of years is never a fixed word in a template.
  var YEARS = {
    en: { one: 'year', other: 'years' },
    es: { one: 'año', other: 'años' },
    uk: { one: 'рік', few: 'роки', many: 'років', other: 'року' },
    ru: { one: 'год', few: 'года', many: 'лет', other: 'года' },
  };

  function yearsWord(n) {
    var forms = YEARS[current] || YEARS.en;
    var rule = 'other';
    try {
      rule = new Intl.PluralRules(LOCALES[current]).select(n);
    } catch (error) {
      /* very old engines: fall back to the general form */
    }
    return forms[rule] || forms.other;
  }

  // "ua" is the country, "uk" the language; people type the first. The code
  // stays "uk", which is what Intl and the lang attribute need.
  function normalise(lang) {
    return lang === 'ua' ? 'uk' : lang;
  }

  function detect(stored) {
    stored = normalise(stored);
    if (stored && STRINGS[stored]) return stored;
    var list = (global.navigator && global.navigator.languages) || [];
    for (var i = 0; i < list.length; i += 1) {
      var code = String(list[i]).slice(0, 2).toLowerCase();
      if (STRINGS[code]) return code;
    }
    return 'en';
  }

  var current = 'en';

  function t(key, params) {
    var value = (STRINGS[current] && STRINGS[current][key]) || STRINGS.en[key] || key;
    if (!params) return value;
    return value.replace(/\{(\w+)\}/g, function (match, name) {
      return params[name] == null ? match : params[name];
    });
  }

  global.TaxI18N = {
    t: t,
    yearsWord: yearsWord,
    detect: detect,
    lang: function () { return current; },
    set: function (lang) {
      lang = normalise(lang);
      current = STRINGS[lang] ? lang : 'en';
      return current;
    },
    locale: function () { return LOCALES[current]; },
    label: function () { return LABELS[current]; },
    next: function () {
      var order = Object.keys(STRINGS);
      return order[(order.indexOf(current) + 1) % order.length];
    },
  };
